# Variable = A container for a value (string, integer, float, boolean) A variable behaves as if it was the value it contains
# Strings
first_name = "aman" 
print(f"Hello {first_name}")
food = "pizza"
print(f"I like {food}")
email = "aman@123.com"
print(f"Your email is : {email}")

# Integer
age = 20
quantity = 4
